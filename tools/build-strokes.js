#!/usr/bin/env node
/*
 * Builds data/strokes.js (stroke outlines + centre lines for every writing character, bundled so the game
 * works offline and from file://). Source: the `hanzi-writer-data` npm package (Make Me a Hanzi data,
 * Arphic Public License — see THIRD_PARTY_NOTICES.md and licenses/ARPHICPL.TXT).
 *
 *   mkdir /tmp/hw && cd /tmp/hw && npm init -y && npm i hanzi-writer-data
 *   node tools/build-strokes.js /tmp/hw/node_modules/hanzi-writer-data
 *
 * Re-run after adding characters to data/writing.js.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const src = process.argv[2];
if (!src || !fs.existsSync(src)) { console.error('usage: node tools/build-strokes.js <path to hanzi-writer-data>'); process.exit(1); }

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data/writing.js'), 'utf8'), ctx);
const W = ctx.window.MSC.data.writing;
const chars = [...W.tutorial, ...W.pool].map((c) => c.char);

/*
 * The upstream data lists the horizontal stroke of 右 first. The standard (PRC) order, which Master Wang
 * teaches, starts with the slanted stroke: 丿一丨𠃍一. Swap the first two strokes of these characters.
 * (A modification of the Arphic-licensed data; noted in the generated file header.)
 */
const SWAP_FIRST_TWO = ['右'];

const out = {};
chars.forEach((c) => {
  const file = path.join(src, `${c}.json`);
  if (!fs.existsSync(file)) { console.error(`missing stroke data for ${c}`); process.exit(1); }
  const d = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (SWAP_FIRST_TWO.includes(c)) {
    [d.strokes[0], d.strokes[1]] = [d.strokes[1], d.strokes[0]];
    [d.medians[0], d.medians[1]] = [d.medians[1], d.medians[0]];
  }
  out[c] = {
    strokes: d.strokes,
    medians: d.medians.map((m) => m.map((p) => [Math.round(p[0]), Math.round(p[1])])),
    rad: d.radStrokes || [],
  };
});

const header = `/*
 * STROKE DATA — generated by tools/build-strokes.js. Do not edit by hand.
 *
 * Derived from Make Me a Hanzi (via the hanzi-writer-data package), distributed under the Arphic Public License
 * (Copyright (C) 1999 Arphic Technology Co., Ltd.). Full text: licenses/ARPHICPL.TXT.
 * Modified: stroke order of ${SWAP_FIRST_TWO.join(', ')} changed to the standard order (first two strokes swapped).
 *
 * Per character:  strokes  SVG outlines (y-up, 1024 box)   medians  centre line of each stroke   rad  radical stroke numbers
 */
`;
fs.writeFileSync(path.join(root, 'data/strokes.js'),
  `${header}(function (MSC) {\n  MSC.data = MSC.data || {};\n  MSC.data.strokes = ${JSON.stringify(out)};\n})(window.MSC = window.MSC || {});\n`);
console.log(`wrote data/strokes.js for ${chars.length} characters (${fs.statSync(path.join(root, 'data/strokes.js')).size} bytes)`);
