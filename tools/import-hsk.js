#!/usr/bin/env node
/*
 * Regenerates data/hsk.js — the official word list the game follows — from the complete-hsk-vocabulary dataset
 * (https://github.com/drkameleon/complete-hsk-vocabulary, MIT). We use its "newest" lists: the revised HSK 3.0 levels.
 *   git clone --depth 1 https://github.com/drkameleon/complete-hsk-vocabulary /tmp/hsk
 *   node tools/import-hsk.js /tmp/hsk [maxLevel=2]
 * Only the level of each word is taken from the dataset; meanings, categories etc. are written by hand in data/dictionary.js
 * and data/vocab/*.js (the validator makes sure every listed word exists there).
 */
const fs = require('fs'), path = require('path');
const src = process.argv[2], max = Number(process.argv[3] || 2);
if (!src) { console.error('usage: node tools/import-hsk.js <path to complete-hsk-vocabulary> [maxLevel]'); process.exit(1); }
const levels = {};
for (let l = 1; l <= max; l++) levels[l] = JSON.parse(fs.readFileSync(path.join(src, 'wordlists/exclusive/newest', `${l}.json`), 'utf8')).map((e) => e.simplified);
const body = Object.entries(levels).map(([l, ws]) => `    ${l}: [\n${ws.map((w) => `'${w}',`).join(' ').replace(/(.{1,110})( |$)/g, '      $1\n')}    ],`).join('\n');
const out = `/*
 * HSK — the words of each level, in the revised HSK 3.0 lists. GENERATED by tools/import-hsk.js from the complete-hsk-vocabulary
 * dataset (MIT, https://github.com/drkameleon/complete-hsk-vocabulary, "newest" lists). Do not edit by hand.
 * Every word here must exist in data/dictionary.js or data/vocab/*.js; its \`hsk\` level is set from this list when the game loads.
 */
(function (MSC) {
  MSC.data = MSC.data || {};
  MSC.data.hsk = {
    standard: 'HSK 3.0 (revised lists)',
    levels: {
${body}
    },
  };
})(window.MSC = window.MSC || {});
`;
fs.writeFileSync(path.join(__dirname, '..', 'data/hsk.js'), out);
console.log('wrote data/hsk.js:', Object.entries(levels).map(([l, w]) => `HSK ${l}: ${w.length}`).join(', '));
